//! PumpSwap (pAMM) — монеты, которые уже «выпустились» с кривой.
//!
//! Нативный билдер pAMM-инструкций требует layout пула (base/quote vaults,
//! lp mint, fee аккаунты и т.д.), который меняется между версиями программы.
//! Чтобы не тащить в продакшн неверную раскладку, обмен по AMM-монетам мы
//! маршрутизируем через Jupiter (jupiter.rs) — он сам знает пулы PumpSwap.
//! Это чуть медленнее на вход (нужен quote-запрос), поэтому если будешь
//! фармить много уже-выпустившихся монет — впиши сюда нативный билдер pAMM
//! по актуальному IDL (program: PUMPSWAP_PROGRAM).
//!
//! На бондинг-кривых (пока complete == false) используем pumpfun.rs напрямую —
//! это основной лоукап-кейс и самый быстрый путь.

use crate::pumpfun::Curve;

/// Выпустилась ли монета с кривой (торгуется ли уже на pAMM).
pub fn is_graduated(curve: &Option<Curve>) -> bool {
    match curve {
        // Нет аккаунта кривой → либо не pump, либо уже мигрировала.
        None => true,
        Some(c) => c.complete,
    }
}
